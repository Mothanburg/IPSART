function C3 = fn_S2_to_C3(S2)

arguments
    S2 (:,:,2,2)
end

X = (S2(:,:,1,2) + S2(:,:,2,1)) / sqrt(2);
C3(:,:,1,1) = S2(:,:,1,1) .* conj(S2(:,:,1,1));
C3(:,:,1,2) = S2(:,:,1,1) .* conj(X);
C3(:,:,1,3) = S2(:,:,1,1) .* conj(S2(:,:,2,2));
C3(:,:,2,1) = conj(C3(:,:,1,2));
C3(:,:,2,2) = X .* conj(X);
C3(:,:,2,3) = X .* conj(S2(:,:,2,2));
C3(:,:,3,1) = conj(C3(:,:,1,3));
C3(:,:,3,2) = conj(C3(:,:,2,3));
C3(:,:,3,3) = S2(:,:,2,2) .* conj(S2(:,:,2,2));

end