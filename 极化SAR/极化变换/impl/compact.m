function C2 = compact(C, mode)

[height,width,~,~] = size(C);
switch mode
    case 'PI/4'
        C2 = zeros(height, width, 2, 2);
        C2(:,:,1,1) = ...
            (C(:,:,1,1)+C(:,:,2,2)/2+sqrt(2)*real(C(:,:,1,2)))/2;
        C2(:,:,1,2) = ...
            (C(:,:,1,3)+C(:,:,2,2)/2+(C(:,:,1,2)+C(:,:,2,3)/sqrt(2)))/2;
        C2(:,:,2,1) = conj(C2(:,:,1,2));
        C2(:,:,2,2) = ...
            (C(:,:,3,3)+C(:,:,2,2)/2+sqrt(2)*real(C(:,:,2,3)))/2;
    case 'CTLR'
        C2 = zeros(height, width, 2, 2);
        C2(:,:,1,1) = ...
            (C(:,:,1,1)+C(:,:,2,2)/2-sqrt(2)*imag(C(:,:,1,2)))/2;
        C2(:,:,1,2) = ...
            (1i*C(:,:,1,3)-1i*C(:,:,2,2)/2+(C(:,:,1,2)+C(:,:,2,3))/...
            sqrt(2))/2;
        C2(:,:,2,1) = conj(C2(:,:,1,2));
        C2(:,:,2,2) = ...
            (C(:,:,3,3)+C(:,:,2,2)/2-sqrt(2)*imag(C(:,:,2,3)))/2;
    case 'hhhv'
        C2 = zeros(height, width, 2, 2);
        C2(:,:,1,1) = C(:,:,1,1);
        C2(:,:,1,2) = C(:,:,1,2)/sqrt(2);
        C2(:,:,2,1) = conj(C2(:,:,1,2));
        C2(:,:,2,2) = C(:,:,2,2)/sqrt(2);
    case 'hhvv'
        C2 = zeros(height, width, 2, 2);
        C2(:,:,1,1) = C(:,:,1,1);
        C2(:,:,1,2) = C(:,:,1,3);
        C2(:,:,2,1) = conj(C2(:,:,1,2));
        C2(:,:,2,2) = C(:,:,3,3);
    otherwise
        error("错误的数据类型");
end

end