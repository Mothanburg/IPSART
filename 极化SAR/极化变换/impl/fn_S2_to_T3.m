function T3 = fn_S2_to_T3(S2)

arguments
    S2 (:,:,2,2)
end

X = (S2(:,:,1,2) + S2(:,:,2,1)) / 2;
T3(:,:,1,1) = (S2(:,:,1,1) + S2(:,:,2,2)) .* conj(S2(:,:,1,1) + S2(:,:,2,2));
T3(:,:,1,2) = (S2(:,:,1,1) + S2(:,:,2,2)) .* conj(S2(:,:,1,1) - S2(:,:,2,2));
T3(:,:,1,3) = 2 * (S2(:,:,1,1) + S2(:,:,2,2)) .* conj(X);
T3(:,:,2,1) = conj(T3(:,:,1,2));
T3(:,:,2,2) = (S2(:,:,1,1) - S2(:,:,2,2)) .* conj(S2(:,:,1,1) - S2(:,:,2,2));
T3(:,:,2,3) = 2 * (S2(:,:,1,1) - S2(:,:,2,2)) .* conj(X);
T3(:,:,3,1) = conj(T3(:,:,1,3));
T3(:,:,3,2) = conj(T3(:,:,2,3));
T3(:,:,3,3) = 4 * X .* conj(X);
T3 = T3 / 2;

end